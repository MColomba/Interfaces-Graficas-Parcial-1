    /** Conecta la pantalla con el controlador y la refresca con los datos actuales. */
    public void setControlador(ControladorSimulacionAPI controlador) {
        if (controlador == null) {
            throw new IllegalArgumentException("El controlador no puede ser null");
        }
        this.controlador = controlador;
        actualizarPantalla();
        btnAvanzarTurno.setEnabled(!controlador.simulacionTerminada());
    }

    /** El panel de intervención que está dentro de esta pantalla (lo maneja ControladorIntervencion). */
    public PanelIntervencion getPanelIntervencion() {
        return panelIntervencion1;
    }

    private void actualizarPantalla() {
        if (controlador == null) {
            return;
        }
        cargarIndicadores(
            controlador.getTurnoActual(),
            controlador.getClimaActual(),
            controlador.getCantidadPlantas(),
            controlador.getCantidadConejos(),
            controlador.getCantidadLobos()
        );
        cargarDatosEnTabla(controlador.getDatosEntidades());
        cargarEventos(controlador.getEventosActuales());
    }

    private void cargarDatosEnTabla(Object[][] datos) {
        DefaultTableModel modelo = (DefaultTableModel) tblEntidades.getModel();
        modelo.setRowCount(0);
        if (datos == null) {
            return;
        }
        for (Object[] fila : datos) {
            modelo.addRow(fila);
        }
    }

    private void cargarEventos(java.util.ArrayList<String> eventos) {
        txtEventos.setText("");
        if (eventos == null) {
            return;
        }
        for (String evento : eventos) {
            txtEventos.append(evento + "\n");
        }
    }

    private void cargarIndicadores(int turno, String clima, int plantas, int conejos, int lobos) {
        lblTurno.setText(String.valueOf(turno));
        lblClima.setText(clima);
        lblPlantas.setText(String.valueOf(plantas));
        lblConejos.setText(String.valueOf(conejos));
        lblLobos.setText(String.valueOf(lobos));
    }

