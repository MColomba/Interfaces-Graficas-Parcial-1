        panelSimulacion = new vista.PanelSimulacio();
        panelReporte = new vista.PanelReporte();

        setDefaultCloseOperation(javax.swing.WindowConstants.EXIT_ON_CLOSE);
        setTitle("EcoSim");

        pnlContenido.setLayout(new java.awt.CardLayout());
        pnlContenido.add(panelConfig, "configuracion");
        pnlContenido.add(panelSimulacion, "simulacion");
