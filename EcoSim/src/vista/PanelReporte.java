    // El controlador llama a este método con el reporte ya armado
    public void cargarReporte(String causaFin, String[][] filas) {
        lblCausaFin.setText(causaFin);
        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) tblReport.getModel();
        modelo.setRowCount(0);                 // borra lo anterior
        for (String[] fila : filas) {
            modelo.addRow(fila);               // una fila por dato
        }
        lblMensaje.setText("");
    }

    // Estado "sin datos": todavía no terminó ninguna simulación
    public void mostrarSinReporte() {
        lblCausaFin.setText("Todavía no hay un reporte.");
        ((javax.swing.table.DefaultTableModel) tblReport.getModel()).setRowCount(0);
        lblMensaje.setText("El reporte aparece cuando termina una simulación.");
    }
